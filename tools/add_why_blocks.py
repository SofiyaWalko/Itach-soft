TEMPLATE = '''        <!-- Почему нам доверяют: карточки с отворотом, раскрывается на наведении -->
        <section class="why" id="why" aria-labelledby="why-title">
          <div class="container">
            <h2 class="section-title" data-reveal id="why-title">
              Почему нам <span class="section-title__muted">доверяют</span>
            </h2>
            <div class="why__scroller">
              <div class="why-cards" data-reveal-stagger>
{cards}
              </div>
            </div>
          </div>
        </section>

'''

CARD = '''              <article class="why-card" tabindex="0">
                <div class="why-card__body">
                  <h3 class="why-card__title">{title}</h3>
                  <p class="why-card__text">{text}</p>
                </div>
                <span class="why-card__sheet" aria-hidden="true"></span>
                <ul class="why-card__facts">{facts}</ul>
                <span class="why-card__fold" aria-hidden="true"></span>
              </article>'''


def build(cards):
    rendered = "\n".join(
        CARD.format(
            title=title,
            text=text,
            facts="".join(f'<li class="why-card__fact">{f}</li>' for f in facts),
        )
        for title, text, facts in cards
    )
    return TEMPLATE.format(cards=rendered)


def insert(name, cards):
    p = Path(name)
    s = p.read_text(encoding="utf-8")
    assert '<section class="why"' not in s, f"{name}: why уже есть"
    anchor = "cases" if '<section class="cases"' in s else "problems"
    m = re.search(rf'<section class="{anchor}".*?</section>', s, re.DOTALL)
    assert m, f"{name}: секция {anchor} не найдена"
    assert m.group(0).count("<section") == 1, f"{name}: вложенная секция"
    block = "\n\n" + build(cards)
    s = s[:m.end()] + block + s[m.end():]
    p.write_text(s, encoding="utf-8")


