def main():
    for name, texts in DATA.items():
        path = ROOT / name
        s = path.read_text(encoding="utf-8")
        start = s.index('class="audience"')
        end = s.index("\n        </section>", start)
        block = s[start:end]
        found = list(TEXT_RE.finditer(block))
        assert len(found) == 6, f"{name}: панелей {len(found)}"
        assert len(texts) == 6, f"{name}: текстов {len(texts)}"
        for i in reversed(range(6)):
            m = found[i]
            block = block[: m.start(2)] + texts[i] + block[m.end(2):]
        path.write_text(s[:start] + block + s[end:], encoding="utf-8")
        print(f"expanded {name}")


if __name__ == "__main__":
    main()
