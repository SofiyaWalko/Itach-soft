def build_tech_stack(tabs):
    """Стек технологий под заголовком «Технологии»: табы по категориям и
    карточки-инструменты — тем же приёмом, что «Ключевые инструменты внедрения»
    на страницах Битрикс24. Лента технологий остаётся под этим блоком."""
    tab_buttons = []
    panels = []
    for i, (label, cards) in enumerate(tabs, 1):
        active = " is-active" if i == 1 else ""
        selected = "true" if i == 1 else "false"
        tabindex = "" if i == 1 else ' tabindex="-1"'
        tab_buttons.append(
            f'                <button class="tools-tab{active}" type="button" role="tab" id="stack-tab-{i}" aria-selected="{selected}" aria-controls="stack-panel-{i}"{tabindex}>\n'
            f'                  <span>{label}</span>\n'
            f'                </button>'
        )
        items = []
        for head, muted, text in cards:
            muted_html = f' <span class="section-title__muted">{muted}</span>' if muted else ""
            items.append(
                f'                  <li class="tools-item glow-card"><h3 class="tools-item__name">{head}{muted_html}</h3><p class="tools-item__text">{text}</p></li>'
            )
        panels.append(
            f'              <div class="tools-panel{active}" role="tabpanel" id="stack-panel-{i}" aria-labelledby="stack-tab-{i}">\n'
            '                <ul class="tools-list">\n'
            + "\n".join(items)
            + "\n                </ul>\n"
            "              </div>"
        )
    return (
        '          <div class="container">\n'
        '            <div class="tools-picker" data-tools-picker data-no-hover-switch data-reveal>\n'
        '              <div class="tools-tabs" role="tablist" aria-label="Группы технологий">\n'
        + "\n".join(tab_buttons)
        + "\n              </div>\n"
        '              <div class="tools-panels">\n'
        + "\n".join(panels)
        + "\n              </div>\n"
        "            </div>\n"
        "          </div>"
    )


def build_team(roles):
    rows = []
    for img, w, h, name, duty in roles:
        rows.append(
            f'              <li class="team-role glow-card">\n'
            f'                <img class="team-role__image" src="assets/img/team/{img}.webp" width="{w}" height="{h}" alt="" loading="lazy" />\n'
            f'                <span class="team-role__name">{name}</span>\n'
            f'                <span class="team-role__duty">{duty}</span>\n'
            f'              </li>'
        )
    return "\n".join(rows)


