def build_audience(segments):
    return audience_carousel.COMMENT + "\n" + audience_carousel.build_section(segments)


def main():
    for name, segments in DATA.items():
        path = ROOT / name
        s = path.read_text(encoding="utf-8")
        if 'class="audience"' in s:
            print(f"skip (already has block): {name}")
            continue
        assert s.count(AWARDS) == 1, f"{name}: не найден маркер достижений"
        s = s.replace(AWARDS, build_audience(segments) + "\n\n" + AWARDS)
        path.write_text(s, encoding="utf-8")
        print(f"audience added: {name}")


if __name__ == "__main__":
    main()
