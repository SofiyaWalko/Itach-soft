ABOUT_TEMPLATE = '''      <div class="service-sections">
        <!-- О направлении -->
        <section class="service-about">
          <div class="container">
            <p class="service-about__statement" data-text-fill>{text}</p>
          </div>
        </section>

'''

for name, text in ABOUT.items():
    p = Path(name)
    s = p.read_text(encoding="utf-8")
    assert 'service-about__statement' not in s, f"{name}: блок уже есть"
    anchor = '      <div class="service-sections">\n'
    assert s.count(anchor) == 1, f"{name}: якорь не уникален"
    s = s.replace(anchor, ABOUT_TEMPLATE.format(text=text), 1)
    p.write_text(s, encoding="utf-8")
    print(f"{name}: вводный блок восстановлен")

for name, data in PAGES.items():
    p = Path(name)
    s = p.read_text(encoding="utf-8")
    # Закрывающий тег сетки — с отступом 12 пробелов (вложенные списки цен — глубже)
    pattern = re.compile(r'            <ul class="format-grid"[^>]*>.*?\n            </ul>', re.DOTALL)
    matches = pattern.findall(s)
    assert len(matches) == 1, f"{name}: найдено {len(matches)} format-grid"
    assert matches[0].count("<ul") == matches[0].count("</ul>"), f"{name}: непарные ul"
    s = pattern.sub(grid(data), s, count=1)
    p.write_text(s, encoding="utf-8")
    print(f"{name}: тарифы вставлены")

