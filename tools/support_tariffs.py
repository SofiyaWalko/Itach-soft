def card(title, price, desc, features, featured=False, badge=None):
    price_html = (
        f'<span class="tariff-card__price-value tariff-card__price-value--text">{price}</span>'
        if price == "Индивидуально"
        else f'<span class="tariff-card__price-value">{price} ₽</span><span class="tariff-card__price-period">/мес</span>'
    )
    badge_html = f'\n                    <span class="tariff-card__badge">{badge}</span>' if badge else ""
    feats = "\n".join(
        '                    <li class="tariff-card__feature">'
        '<span class="tariff-card__check" aria-hidden="true">'
        '<svg class="icon"><use href="#icon-check" /></svg></span>'
        f'{f}</li>'
        for f in features
    )
    cls = "tariff-card tariff-card--featured glow-card" if featured else "tariff-card glow-card"
    return f'''              <li class="{cls}">
                <div class="tariff-card__head">
                  <div class="tariff-card__title-row">
                    <h3 class="tariff-card__title">{title}</h3>{badge_html}
                  </div>
                  <p class="tariff-card__price">{price_html}</p>
                  <p class="tariff-card__desc">{desc}</p>
                  <a class="btn btn--primary btn--sm tariff-card__cta" href="#lead">Выбрать тариф</a>
                </div>
                <ul class="tariff-card__features">
{feats}
                </ul>
              </li>'''


def plan(data):
    return "\n".join([
        card(*data[0]),
        card(*data[1]),
        card(*data[2]),
        card(*data[3], featured=True, badge="24/7"),
    ])


def grid(data):
    return '            <ul class="tariff-grid" data-reveal-stagger>\n' + plan(data) + "\n            </ul>"


